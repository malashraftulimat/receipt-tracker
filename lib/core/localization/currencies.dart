// ISO 4217 currency catalog — the single source of currency data.
// Currency names are localized data (ja / en / ar), like the message maps.
// Do not hardcode currency symbols or decimal digits anywhere else.

import '../localization/app_language.dart';

class Currency {
  const Currency({
    required this.code,
    required this.symbol,
    required this.decimalDigits,
    required this.nameJa,
    required this.nameEn,
    required this.nameAr,
  });

  final String code;
  final String symbol;
  final int decimalDigits;
  final String nameJa;
  final String nameEn;
  final String nameAr;

  String name(AppLanguage language) => switch (language) {
        AppLanguage.ja => nameJa,
        AppLanguage.en => nameEn,
        AppLanguage.ar => nameAr,
      };

  /// Matches a search query against the code, symbol or any language name.
  bool matches(String query) {
    final q = query.trim().toLowerCase();
    if (q.isEmpty) return true;
    return code.toLowerCase().contains(q) ||
        symbol.toLowerCase().contains(q) ||
        nameJa.toLowerCase().contains(q) ||
        nameEn.toLowerCase().contains(q) ||
        nameAr.contains(q);
  }

  @override
  String toString() => code;
}

